function M.get_banks()
  local result = {}
  for name, info in pairs(M.banks) do
    table.insert(result, {
      name = name,
      description = info.description,
      file_count = #info.files,
    })
  end
  table.sort(result, function(a, b) return a.name < b.name end)
  return result
end

function M.get_files(name)
  local bank = M.banks[name]
  if not bank then
    return {}
  end
  return bank.files
end

return M